import { createAudioPlayer, type AudioPlayer } from "expo-audio";
import * as Haptics from "expo-haptics";

/**
 * The tick and tap that confirm a slide-to-focus.
 *
 * Two signals rather than one, and the haptic is the senior partner. A phone is often on silent
 * and often in a pocket, so sound alone confirms nothing much of the time; a tap is felt either
 * way. The sound exists so the gesture has a voice when the phone is out and audible, and it is
 * mixed low on purpose - this plays several times a day, every day, and a bright sound at full
 * level becomes tiring long before a quiet one does.
 *
 * `assets/sounds/foyg_slide.wav` is 130ms, generated by scripts/make-slide-sound.py. Short
 * because the push to the session screen takes 220ms, and a sound still playing on the next
 * screen belongs to neither.
 *
 * Nothing here is allowed to matter. Audio and haptics are both unavailable on some devices and
 * in the browser the e2e suite runs in, and a session must start whether or not the phone can
 * make a noise about it - so every call is fire-and-forget behind its own guard.
 */

/** Built on first use rather than at import, so a failing module can't break the bundle. */
let player: AudioPlayer | null = null;
let unavailable = false;

function sound(): AudioPlayer | null {
  if (unavailable) return null;
  if (!player) {
    try {
      player = createAudioPlayer(require("../../assets/sounds/foyg_slide.wav"));
    } catch {
      unavailable = true;
      return null;
    }
  }
  return player;
}

/**
 * Fired the moment the knob reaches the end, not when the session comes back.
 *
 * Confirming the *gesture* is the point: the server round trips take a few hundred milliseconds,
 * and feedback that waits for them reads as lag rather than as acknowledgement.
 */
export function playSlideCommit(): void {
  try {
    // Light, not Medium: this is a confirmation, not an alert, and it sits under a quiet sound.
    void Haptics.impactAsync(Haptics.ImpactFeedbackStyle.Light).catch(() => {});
  } catch {
    // No vibrator, or a browser. The sound below still stands in.
  }
  try {
    const p = sound();
    if (!p) return;
    // Rewound first: a second slide inside 130ms would otherwise be silent, because the player
    // is already sitting at the end of the clip.
    void Promise.resolve(p.seekTo(0))
      .then(() => p.play())
      .catch(() => {});
  } catch {
    // Audio focus denied, file missing, platform without playback - never worth a crash.
  }
}
